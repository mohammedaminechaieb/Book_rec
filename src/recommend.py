
"""
==============================================================================
File      : src/recommend.py
Project   : book_rec - Reducing popularity bias in book recommendation
Owner     : Ella (lead) | Amine (co-owner / reviewer)
------------------------------------------------------------------------------
What it does:
  Shared recommendation logic for Streamlit and the command line.

  1. load_artifacts(): loads trained models and saved data.
  2. recommend_for_user(): recommends books for an existing reader.
  3. recommend_for_new_reader(): uses content similarity for cold users.
  4. main(): command-line interface.

Input:
  - config/config.yaml
  - data/processed/* generated by run_pipeline.py
  - results/tables/best_k.json (optional)

Output:
  - DataFrame [rank, book_id, title, score, n, alpha, cf_share, content_share,
               popularity, explanation]   (popularity = head / mid / tail, see src/labels.py)
  - editions of a book already read / picked are never recommended (src/editions.py)
  - results/tables/demo_<user_id>.csv
==============================================================================
"""

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.preprocessing import normalize

from src.utils.config import load_config
from src.utils.io import load_df, load_sparse

from src.models.als_model import ALSModel
from src.models.popularity import PopularityModel
from src.models.hybrid_gate import HybridGate, minmax_rows
from src.models.content_tfidf import ContentTFIDFModel

from src.editions import dedupe_candidates
from src.explain import (
    explain,
    frequent_shelves,
    popularity_label,
    shared_shelves,
)
from src.labels import NBSP, popularity_thresholds


COLUMNS = [
    "rank",
    "book_id",
    "title",
    "score",
    "n",
    "alpha",
    "cf_share",
    "content_share",
    "popularity",
    "explanation",
]

# How many extra candidates to look at, so that removing other editions
# of already-read books still leaves top_n recommendations.
CANDIDATE_FACTOR = 5


def _read_json(path: Path) -> dict:
    """Load a JSON file."""
    with Path(path).open("r", encoding="utf-8") as f:
        return json.load(f)


def _validate_top_n(top_n: int) -> None:
    """Check that the number of recommendations is valid."""
    if top_n < 1:
        raise ValueError("top_n must be positive.")


def _shelves(value) -> list[str]:
    """Return shelf tags as a clean list of strings."""
    if isinstance(value, (list, tuple, np.ndarray)):
        return [str(x) for x in value]
    return []


def load_artifacts(cfg: dict) -> dict:
    """
    Load the saved models and data without retraining.

    Returns a dictionary used by the recommendation functions.
    """

    processed = Path(cfg["paths"]["processed_dir"])
    tables = Path(cfg["paths"]["tables_dir"])

    required = [
        processed / "id_maps.json",
        processed / "train_csr.npz",
        processed / "n_items.npy",
        processed / "als_factors.npz",
        processed / "tfidf_items.npz",
        processed / "books_aligned.parquet",
    ]

    missing = [
        str(path)
        for path in required
        if not path.exists()
    ]

    if missing:
        raise FileNotFoundError(
            "Missing pipeline artifacts:\n"
            + "\n".join(missing)
            + "\nRun the complete pipeline first."
        )

    # Load user and book mappings.
    maps = _read_json(processed / "id_maps.json")

    user2idx = {
        str(key): int(value)
        for key, value in maps["user2idx"].items()
    }

    book2idx = {
        str(key): int(value)
        for key, value in maps["book2idx"].items()
    }

    # Load training matrix and book metadata.
    train = load_sparse(processed / "train_csr.npz")

    books = load_df(
        processed / "books_aligned.parquet"
    )

    n_items = np.load(
        processed / "n_items.npy"
    )

    item_vectors = load_sparse(
        processed / "tfidf_items.npz"
    )

    n_users, n_books = train.shape

    # Check matrix dimensions.
    if (
        len(user2idx) != n_users
        or len(book2idx) != n_books
        or len(books) != n_books
        or len(n_items) != n_books
        or item_vectors.shape[0] != n_books
    ):
        raise ValueError(
            "Artifact dimensions do not match."
        )

    # Reconstruct book order.
    idx2book = sorted(
        book2idx,
        key=book2idx.get
    )

    actual_ids = books["book_id"].astype(str).tolist()

    if idx2book != actual_ids:
        raise ValueError(
            "Book metadata is not aligned with CSR columns."
        )

    # Load ALS factors.
    als = ALSModel.load(
        processed / "als_factors.npz"
    )

    if (
        als.user_factors.shape[0] != n_users
        or als.item_factors.shape[0] != n_books
    ):
        raise ValueError(
            "ALS factors are not aligned."
        )

    # Reconstruct TF-IDF model.
    # Constructor parameters must come from config.yaml.
    t = cfg["tfidf"]

    content = ContentTFIDFModel(
        max_features=t["max_features"],
        min_df=t["min_df"],
        ngram_range=t["ngram_range"],
        use_description=t["use_description"],
        use_shelves=t["use_shelves"],
    )

    # Reuse previously fitted item vectors.
    content.item_vectors = item_vectors
    content.train = train

    # Reconstruct popularity baseline.
    popularity = PopularityModel().fit(train)

    # Load the best k when tuning results are available.
    best_path = tables / "best_k.json"

    if best_path.exists():
        k = float(_read_json(best_path)["k"])
    else:
        k = float(cfg["gate"]["k"])

    # Fixed 50/50 baseline, so the demo can show it too.
    fixed_gate = HybridGate(
        als,
        content,
        n_items,
        k=None,
        fixed_alpha=cfg["gate"]["fixed_alpha"],
    )

    # Reconstruct hybrid model.
    gate = HybridGate(
        als,
        content,
        n_items,
        k=k,
    )

    # Select the demo readers for the Streamlit app.
    # Most users have short histories (after the 5-per-user filter and the
    # time split, a user with 5 books keeps only 3 in train), and the
    # simulated cold users keep exactly 3 on purpose. A demo needs readers
    # with a real history, so: exclude cold users and prefer users with at
    # least app.min_demo_books training books (random sample among them).
    idx2user = {
        idx: uid
        for uid, idx in user2idx.items()
    }

    cold_path = processed / "cold_users.json"
    cold_ids = (
        set(_read_json(cold_path)["user_ids"])
        if cold_path.exists()
        else set()
    )

    books_per_user = train.getnnz(axis=1)
    warm_users = np.array([
        i for i in np.flatnonzero(books_per_user > 0)
        if idx2user[int(i)] not in cold_ids
    ], dtype=int)

    min_books = int(cfg["app"].get("min_demo_books", 8))
    n_wanted = int(cfg["app"]["n_demo_users"])

    rich = warm_users[books_per_user[warm_users] >= min_books]

    rng = np.random.default_rng(cfg["seed"])

    if len(rich) >= n_wanted:
        selected = rng.choice(rich, size=n_wanted, replace=False)
    else:
        # Not enough rich readers: take the longest histories first.
        order = np.argsort(-books_per_user[warm_users], kind="stable")
        selected = warm_users[order[:n_wanted]]

    demo_users = [
        idx2user[int(i)]
        for i in selected
    ]

    # Tags carried by more than 30 % of the books ("comics", "graphic-novels")
    # explain nothing in a comics dataset: never show them as shared tags.
    common_shelves = frequent_shelves(
        _shelves(value) for value in books["shelves"]
    )

    return {
        "cfg": cfg,
        "common_shelves": common_shelves,
        "pop_thresholds": popularity_thresholds(n_items),
        "train": train,
        "books": books,
        "user2idx": user2idx,
        "book2idx": book2idx,
        "idx2book": idx2book,
        "n_items": n_items,
        "item_vectors": item_vectors,
        "als": als,
        "content": content,
        "popularity_model": popularity,
        "gate": gate,
        "fixed_gate": fixed_gate,
        "k": k,
        "demo_users": demo_users,
    }


def _ranked_candidates(scores: np.ndarray, n_wanted: int) -> np.ndarray:
    """Indices of the n_wanted best finite scores, best first."""
    scores = np.asarray(scores, dtype=float).copy()
    scores[~np.isfinite(scores)] = -np.inf
    candidates = np.flatnonzero(np.isfinite(scores))
    if candidates.size == 0:
        return candidates
    order = np.argsort(-scores[candidates], kind="stable")
    return candidates[order[:n_wanted]]


def _drop_other_editions(candidates: np.ndarray, reference_idx, books: pd.DataFrame,
                         top_n: int) -> np.ndarray:
    """Keep the first top_n candidates that are not editions of a reference book."""
    titles = books["title"].astype(str)
    keep = dedupe_candidates(
        [titles.iloc[i] for i in candidates],
        [titles.iloc[i] for i in reference_idx],
        top_n,
    )
    return candidates[keep]


def recommend_for_user(
    user_id: str,
    art: dict,
    model_name: str = "gate",
    top_n: int = 10
) -> pd.DataFrame:
    """
    Recommend unseen books to an existing user.

    Supported models:
        gate, fixed (50/50), als, content, popularity
    Other editions of books the user already read are skipped.
    """
    _validate_top_n(top_n)

    user_id = str(user_id)
    user2idx = art["user2idx"]

    if user_id not in user2idx:
        raise ValueError(f"Unknown user: {user_id}")

    models = {
        "gate": art["gate"],
        "fixed": art["fixed_gate"],
        "als": art["als"],
        "content": art["content"],
        "popularity": art["popularity_model"],
    }

    if model_name not in models:
        raise ValueError(f"Unknown model: {model_name}")

    user_idx = user2idx[user_id]
    batch = np.array([user_idx])

    # Compute recommendation scores.
    scores = np.asarray(models[model_name].score(batch), dtype=float)[0].copy()

    # Normalized branch scores (the values the gate mixes) for explanations.
    cf_scores = minmax_rows(art["als"].score(batch))[0]
    content_scores = minmax_rows(art["content"].score(batch))[0]

    train = art["train"]
    books = art["books"]
    n_items = art["n_items"]

    # Do not recommend already-read books, nor other editions of them.
    seen = train[user_idx].indices
    scores[seen] = -np.inf
    candidates = _ranked_candidates(scores, top_n * CANDIDATE_FACTOR)
    selected_books = _drop_other_editions(candidates, seen, books, top_n)

    if selected_books.size == 0:
        return pd.DataFrame(columns=COLUMNS)

    cfg = art["cfg"]
    rows = []

    for rank, book_idx in enumerate(selected_books, start=1):
        book_idx = int(book_idx)
        n = int(n_items[book_idx])

        # Explanation generated by Amine's module, written for the model shown.
        details = explain(
            user_idx=user_idx,
            book_idx=book_idx,
            train=train,
            item_vectors=art["item_vectors"],
            books=books,
            n_items=n_items,
            k=art["k"],
            cf_score=float(cf_scores[book_idx]),
            content_score=float(content_scores[book_idx]),
            top_shelves=cfg["app"]["explain_top_shelves"],
            cold_threshold=cfg["cold_start"]["cold_threshold"],
            exclude_shelves=art["common_shelves"],
            alpha=art["cfg"]["gate"]["fixed_alpha"] if model_name == "fixed" else None,
            mode={"content": "content", "als": "als", "popularity": "als",
                  "fixed": "fixed"}.get(model_name, "gate"),
        )

        explanation = details["sentence"]
        is_hybrid = model_name in ("gate", "fixed")

        if model_name == "popularity":
            explanation = (
                "Recommandé car c'est l'un des livres les plus lus "
                f"({n}{NBSP}lecteurs dans l'entraînement)."
            )

        rows.append({
            "rank": rank,
            "book_id": str(books.iloc[book_idx]["book_id"]),
            "title": str(books.iloc[book_idx]["title"]),
            "score": float(scores[book_idx]),
            "n": n,
            # The ALS / content split only means something for the hybrid.
            "alpha": float(details["alpha"]) if is_hybrid else float("nan"),
            "cf_share": float(details["cf_share"]) if is_hybrid else float("nan"),
            "content_share": float(details["content_share"]) if is_hybrid else float("nan"),
            "popularity": details["popularity"],
            "explanation": explanation,
        })

    return pd.DataFrame(rows, columns=COLUMNS)


def recommend_for_new_reader(
    book_ids: list[str],
    art: dict,
    top_n: int = 10
) -> pd.DataFrame:
    """
    Generate recommendations for a new reader.

    Since the reader has no ALS factors, use TF-IDF
    similarity based on selected liked books (alpha = 0).
    Other editions of the picked books are skipped.
    """
    _validate_top_n(top_n)

    book2idx = art["book2idx"]

    # Remove duplicate selected IDs.
    selected_ids = list(dict.fromkeys(str(book_id) for book_id in book_ids))
    selected_idx = [book2idx[book_id] for book_id in selected_ids if book_id in book2idx]

    if not selected_idx:
        raise ValueError("Choose at least one known book.")

    item_vectors = art["item_vectors"]

    # Build a mean profile from selected book vectors, then L2-normalize it.
    profile = normalize(np.asarray(item_vectors[selected_idx].mean(axis=0)), norm="l2")

    # Cosine similarity between profile and all books.
    scores = np.asarray(item_vectors @ profile.T).ravel().astype(float)

    # Exclude the selected books and their other editions.
    scores[selected_idx] = -np.inf
    books = art["books"]
    candidates = _ranked_candidates(scores, top_n * CANDIDATE_FACTOR)
    chosen = _drop_other_editions(candidates, selected_idx, books, top_n)

    if chosen.size == 0:
        return pd.DataFrame(columns=COLUMNS)

    n_items = art["n_items"]
    cfg = art["cfg"]
    liked_shelves = [_shelves(books.iloc[i]["shelves"]) for i in selected_idx]

    rows = []

    for rank, book_idx in enumerate(chosen, start=1):
        book_idx = int(book_idx)

        # Find the selected book most similar to the candidate.
        similarities = (item_vectors[selected_idx] @ item_vectors[book_idx].T).toarray().ravel()
        closest = selected_idx[int(np.argmax(similarities))]
        closest_title = str(books.iloc[closest]["title"]).strip().rstrip(".").strip()

        # Find shared, informative shelf tags.
        tags = shared_shelves(
            _shelves(books.iloc[book_idx]["shelves"]),
            liked_shelves,
            top=cfg["app"]["explain_top_shelves"],
            exclude=art["common_shelves"],
        )

        explanation = f"Parce que vous avez aimé « {closest_title} »."
        if tags:
            explanation += f" Tags communs{NBSP}: " + ", ".join(tags) + "."
        explanation += " Recommandé par similarité de contenu."

        n = int(n_items[book_idx])
        rows.append({
            "rank": rank,
            "book_id": str(books.iloc[book_idx]["book_id"]),
            "title": str(books.iloc[book_idx]["title"]),
            "score": float(scores[book_idx]),
            "n": n,
            "alpha": 0.0,
            "cf_share": 0.0,
            "content_share": 1.0,
            "popularity": popularity_label(n, n_items),
            "explanation": explanation,
        })

    return pd.DataFrame(rows, columns=COLUMNS)


def main() -> None:
    """Command-line recommendation demo."""

    parser = argparse.ArgumentParser(
        description="BookRec recommendation demo"
    )

    parser.add_argument(
        "--user",
        required=True,
        help="Existing Goodreads user ID",
    )

    parser.add_argument(
        "--model",
        choices=[
            "gate",
            "fixed",
            "als",
            "content",
            "popularity",
        ],
        default="gate",
    )

    parser.add_argument(
        "--top",
        type=int,
        default=None,
    )

    args = parser.parse_args()

    # Load config and previously trained models.
    cfg = load_config()
    art = load_artifacts(cfg)

    top_n = (
        cfg["app"]["default_top_n"]
        if args.top is None
        else args.top
    )

    # Generate recommendations.
    recommendations = recommend_for_user(
        user_id=args.user,
        art=art,
        model_name=args.model,
        top_n=top_n,
    )

    print(
        recommendations.to_string(index=False)
    )

    # Sanitize user ID for filename.
    safe_id = re.sub(
        r"[^a-zA-Z0-9_-]",
        "_",
        str(args.user),
    )

    output_dir = Path(
        cfg["paths"]["tables_dir"]
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    output_path = (
        output_dir / f"demo_{safe_id}.csv"
    )

    recommendations.to_csv(
        output_path,
        index=False
    )

    print(
        f"\nSaved recommendations to {output_path}"
    )


if __name__ == "__main__":
    main()
