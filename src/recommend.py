import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.preprocessing import normalize

from src.utils.config import load_config
from src.utils.io import load_df, load_sparse

from src.models.als_model import ALSModel
from src.models.popularity import PopularityModel
from src.models.hybrid_gate import HybridGate, minmax_rows
from src.models.content_tfidf import ContentTFIDFModel

from src.explain import (
    explain,
    popularity_label,
    shared_shelves,
)


COLUMNS = [
    "rank",
    "title",
    "score",
    "alpha",
    "popularity",
    "explanation",
]


def _read_json(path: Path) -> dict:
    """Load a JSON file."""
    with Path(path).open("r", encoding="utf-8") as f:
        return json.load(f)


def _validate_top_n(top_n: int) -> None:
    """Check that the number of recommendations is valid."""
    if top_n < 1:
        raise ValueError("top_n must be positive.")


def _shelves(value) -> list[str]:
    """Return shelf tags as a clean list of strings."""
    if isinstance(value, (list, tuple, np.ndarray)):
        return [str(x) for x in value]
    return []


def load_artifacts(cfg: dict) -> dict:
    """
    Load the saved models and data without retraining.

    Returns a dictionary used by the recommendation functions.
    """

    processed = Path(cfg["paths"]["processed_dir"])
    tables = Path(cfg["paths"]["tables_dir"])

    required = [
        processed / "id_maps.json",
        processed / "train_csr.npz",
        processed / "n_items.npy",
        processed / "als_factors.npz",
        processed / "tfidf_items.npz",
        processed / "books_aligned.parquet",
    ]

    missing = [
        str(path)
        for path in required
        if not path.exists()
    ]

    if missing:
        raise FileNotFoundError(
            "Missing pipeline artifacts:\n"
            + "\n".join(missing)
            + "\nRun the complete pipeline first."
        )

    # Load user and book mappings.
    maps = _read_json(processed / "id_maps.json")

    user2idx = {
        str(key): int(value)
        for key, value in maps["user2idx"].items()
    }

    book2idx = {
        str(key): int(value)
        for key, value in maps["book2idx"].items()
    }

    # Load training matrix and book metadata.
    train = load_sparse(processed / "train_csr.npz")

    books = load_df(
        processed / "books_aligned.parquet"
    )

    n_items = np.load(
        processed / "n_items.npy"
    )

    item_vectors = load_sparse(
        processed / "tfidf_items.npz"
    )

    n_users, n_books = train.shape

    # Check matrix dimensions.
    if (
        len(user2idx) != n_users
        or len(book2idx) != n_books
        or len(books) != n_books
        or len(n_items) != n_books
        or item_vectors.shape[0] != n_books
    ):
        raise ValueError(
            "Artifact dimensions do not match."
        )

    # Reconstruct book order.
    idx2book = sorted(
        book2idx,
        key=book2idx.get
    )

    actual_ids = books["book_id"].astype(str).tolist()

    if idx2book != actual_ids:
        raise ValueError(
            "Book metadata is not aligned with CSR columns."
        )

    # Load ALS factors.
    als = ALSModel.load(
        processed / "als_factors.npz"
    )

    if (
        als.user_factors.shape[0] != n_users
        or als.item_factors.shape[0] != n_books
    ):
        raise ValueError(
            "ALS factors are not aligned."
        )

    # Reconstruct TF-IDF model.
    # Constructor parameters must come from config.yaml.
    t = cfg["tfidf"]

    content = ContentTFIDFModel(
        max_features=t["max_features"],
        min_df=t["min_df"],
        ngram_range=t["ngram_range"],
        use_description=t["use_description"],
        use_shelves=t["use_shelves"],
    )

    # Reuse previously fitted item vectors.
    content.item_vectors = item_vectors
    content.train = train

    # Reconstruct popularity baseline.
    popularity = PopularityModel().fit(train)

    # Load the best k when tuning results are available.
    best_path = tables / "best_k.json"

    if best_path.exists():
        k = float(_read_json(best_path)["k"])
    else:
        k = float(cfg["gate"]["k"])

    # Reconstruct hybrid model.
    gate = HybridGate(
        als,
        content,
        n_items,
        k=k,
    )

    # Select active users for the Streamlit demo.
    active_users = np.flatnonzero(
        train.getnnz(axis=1) > 0
    )

    rng = np.random.default_rng(cfg["seed"])

    n_demo = min(
        cfg["app"]["n_demo_users"],
        len(active_users),
    )

    if n_demo > 0:
        selected = rng.choice(
            active_users,
            size=n_demo,
            replace=False,
        )
    else:
        selected = np.array([], dtype=int)

    idx2user = {
        idx: uid
        for uid, idx in user2idx.items()
    }

    demo_users = [
        idx2user[int(i)]
        for i in selected
    ]

    return {
        "cfg": cfg,
        "train": train,
        "books": books,
        "user2idx": user2idx,
        "book2idx": book2idx,
        "idx2book": idx2book,
        "n_items": n_items,
        "item_vectors": item_vectors,
        "als": als,
        "content": content,
        "popularity_model": popularity,
        "gate": gate,
        "k": k,
        "demo_users": demo_users,
    }


def recommend_for_user(
    user_id: str,
    art: dict,
    model_name: str = "gate",
    top_n: int = 10
) -> pd.DataFrame:
    """
    Recommend unseen books to an existing user.

    Supported models:
        gate, als, content, popularity
    """

    _validate_top_n(top_n)

    user_id = str(user_id)
    user2idx = art["user2idx"]

    if user_id not in user2idx:
        raise ValueError(
            f"Unknown user: {user_id}"
        )

    models = {
        "gate": art["gate"],
        "als": art["als"],
        "content": art["content"],
        "popularity": art["popularity_model"],
    }

    if model_name not in models:
        raise ValueError(
            f"Unknown model: {model_name}"
        )

    user_idx = user2idx[user_id]
    batch = np.array([user_idx])

    # Compute recommendation scores.
    model = models[model_name]

    scores = np.asarray(
        model.score(batch),
        dtype=float,
    )[0].copy()

    # Get normalized branch scores for explanations.
    cf_scores = minmax_rows(
        art["als"].score(batch)
    )[0]

    content_scores = minmax_rows(
        art["content"].score(batch)
    )[0]

    train = art["train"]

    # Do not recommend already-read books.
    seen = train[user_idx].indices

    scores[seen] = -np.inf

    # Exclude invalid scores.
    scores[~np.isfinite(scores)] = -np.inf

    candidates = np.flatnonzero(
        np.isfinite(scores)
    )

    if candidates.size == 0:
        return pd.DataFrame(columns=COLUMNS)

    n_select = min(
        top_n,
        len(candidates)
    )

    order = np.argsort(
        -scores[candidates],
        kind="stable"
    )[:n_select]

    selected_books = candidates[order]

    rows = []

    for rank, book_idx in enumerate(
        selected_books,
        start=1
    ):

        book_idx = int(book_idx)

        if model_name == "als":
            alpha_override = 1.0

        elif model_name == "content":
            alpha_override = 0.0

        elif model_name == "popularity":
            alpha_override = 1.0

        else:
            alpha_override = None

        # Explanation generated by Amine's module.
        details = explain(
            user_idx=user_idx,
            book_idx=book_idx,
            train=train,
            item_vectors=art["item_vectors"],
            books=art["books"],
            n_items=art["n_items"],
            k=art["k"],
            cf_score=float(cf_scores[book_idx]),
            content_score=float(content_scores[book_idx]),
            top_shelves=art["cfg"]["app"]["explain_top_shelves"],
            alpha=alpha_override,
            cold_threshold=art["cfg"]["cold_start"]["cold_threshold"],
        )

        explanation = details["sentence"]

        if model_name == "popularity":
            explanation = (
                "Recommended because this book has "
                f"{int(art['n_items'][book_idx])} "
                "training interactions."
            )

        rows.append({
            "rank": rank,
            "title": str(
                art["books"].iloc[book_idx]["title"]
            ),
            "score": float(scores[book_idx]),
            "alpha": (
                float("nan")
                if model_name == "popularity"
                else float(details["alpha"])
            ),
            "popularity": details["popularity"],
            "explanation": explanation,
        })

    return pd.DataFrame(
        rows,
        columns=COLUMNS
    )


def recommend_for_new_reader(
    book_ids: list[str],
    art: dict,
    top_n: int = 10
) -> pd.DataFrame:
    """
    Generate recommendations for a new reader.

    Since the reader has no ALS factors, use TF-IDF
    similarity based on selected liked books.
    """

    _validate_top_n(top_n)

    book2idx = art["book2idx"]

    # Remove duplicate selected IDs.
    selected_ids = list(
        dict.fromkeys(
            str(book_id)
            for book_id in book_ids
        )
    )

    selected_idx = [
        book2idx[book_id]
        for book_id in selected_ids
        if book_id in book2idx
    ]

    if not selected_idx:
        raise ValueError(
            "Choose at least one known book."
        )

    item_vectors = art["item_vectors"]

    # Build a mean profile from selected book vectors.
    profile = np.asarray(
        item_vectors[selected_idx].mean(axis=0)
    )

    # L2 normalization.
    profile = normalize(
        profile,
        norm="l2"
    )

    # Cosine similarity between profile and all books.
    scores = np.asarray(
        item_vectors @ profile.T
    ).ravel().astype(float)

    # Exclude the selected books.
    scores[selected_idx] = -np.inf

    # Ignore invalid scores.
    scores[~np.isfinite(scores)] = -np.inf

    candidates = np.flatnonzero(
        np.isfinite(scores)
    )

    if candidates.size == 0:
        return pd.DataFrame(columns=COLUMNS)

    n_select = min(
        top_n,
        len(candidates)
    )

    order = np.argsort(
        -scores[candidates],
        kind="stable"
    )[:n_select]

    chosen = candidates[order]

    books = art["books"]
    n_items = art["n_items"]

    liked_shelves = [
        _shelves(books.iloc[i]["shelves"])
        for i in selected_idx
    ]

    rows = []

    for rank, book_idx in enumerate(
        chosen,
        start=1
    ):

        book_idx = int(book_idx)

        # Find the selected book most similar to the candidate.
        similarities = (
            item_vectors[selected_idx]
            @ item_vectors[book_idx].T
        ).toarray().ravel()

        closest = selected_idx[
            int(np.argmax(similarities))
        ]

        # Find shared shelf tags.
        tags = shared_shelves(
            _shelves(books.iloc[book_idx]["shelves"]),
            liked_shelves,
            top=art["cfg"]["app"]["explain_top_shelves"],
        )

        explanation = (
            f"Because you liked {books.iloc[closest]['title']}."
        )

        if tags:
            explanation += (
                " Shared tags: "
                + ", ".join(tags)
                + "."
            )

        explanation += (
            " Recommended using content similarity."
        )

        rows.append({
            "rank": rank,
            "title": str(
                books.iloc[book_idx]["title"]
            ),
            "score": float(scores[book_idx]),
            "alpha": 0.0,
            "popularity": popularity_label(
                int(n_items[book_idx]),
                n_items,
                art["cfg"]["cold_start"]["cold_threshold"],
            ),
            "explanation": explanation,
        })

    return pd.DataFrame(
        rows,
        columns=COLUMNS
    )


def main() -> None:
    """Command-line recommendation demo."""

    parser = argparse.ArgumentParser(
        description="BookRec recommendation demo"
    )

    parser.add_argument(
        "--user",
        required=True,
        help="Existing Goodreads user ID",
    )

    parser.add_argument(
        "--model",
        choices=[
            "gate",
            "als",
            "content",
            "popularity",
        ],
        default="gate",
    )

    parser.add_argument(
        "--top",
        type=int,
        default=None,
    )

    args = parser.parse_args()

    # Load config and previously trained models.
    cfg = load_config()
    art = load_artifacts(cfg)

    top_n = (
        cfg["app"]["default_top_n"]
        if args.top is None
        else args.top
    )

    # Generate recommendations.
    recommendations = recommend_for_user(
        user_id=args.user,
        art=art,
        model_name=args.model,
        top_n=top_n,
    )

    print(
        recommendations.to_string(index=False)
    )

    # Sanitize user ID for filename.
    safe_id = re.sub(
        r"[^a-zA-Z0-9_-]",
        "_",
        str(args.user),
    )

    output_dir = Path(
        cfg["paths"]["tables_dir"]
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    output_path = (
        output_dir / f"demo_{safe_id}.csv"
    )

    recommendations.to_csv(
        output_path,
        index=False
    )

    print(
        f"\nSaved recommendations to {output_path}"
    )


if __name__ == "__main__":
    main()
